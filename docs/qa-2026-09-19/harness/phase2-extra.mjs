import fs from 'node:fs';
import path from 'node:path';
import { Client, Evidence, adminClient, here, must, privateConfig } from './client.mjs';
const e=new Evidence('phase2-extra-evidence');
const admin=await adminClient(e);
const m=JSON.parse(fs.readFileSync(path.join(here,'data-manifest.json'),'utf8'));
const bank=JSON.parse(fs.readFileSync(path.join(here,'bank-manifest.json'),'utf8'));
const c=new Client({evidence:e});must(await c.login(m.users.find(x=>x.key==='eng'&&x.role==='Instructor').email,privateConfig().password),'Login');
const save=()=>fs.writeFileSync(path.join(here,'bank-manifest.json'),JSON.stringify(bank,null,2));
const image=bank.media[0].file??bank.media[0];
bank.media[0]=image;
const q=bank.questions.find(x=>x.key==='single');
const at=must(await c.post(`/api/QuestionBank/questions/${q.id}/attachments`,{questionId:q.id,fileName:image.originalFileName,filePath:image.url,fileType:'Image',fileSize:image.sizeInBytes,isPrimary:true}),'Attach valid uploaded image');
const attachments=must(await c.get(`/api/QuestionBank/questions/${q.id}/attachments`),'Read attachments');
e.check('Uploaded image attached and primary flag persists',attachments.some(x=>x.id===at.id&&x.filePath===image.url&&x.isPrimary),attachments);
q.attachments=attachments;save();
const bytes=await fetch(`${c.base}${image.url}`,{headers:{Authorization:`Bearer ${c.token}`}});
e.check('Attached image bytes can be fetched for authorized instructor',bytes.ok&&(await bytes.arrayBuffer()).byteLength===image.sizeInBytes,{status:bytes.status});
const pdf=Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n2 0 obj<</Type/Pages/Kids[]/Count 0>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF');
const pu=await c.upload('/api/Media/upload?folder=questions',pdf,'qa26-test-reference.pdf','application/pdf');
e.check('PDF media upload accepted',pu.ok,pu.body);
if(pu.ok){
 const pf=pu.body.file;bank.media.push(pf);save();
 const pa=must(await c.post(`/api/QuestionBank/questions/${q.id}/attachments`,{questionId:q.id,fileName:pf.originalFileName,filePath:pf.url,fileType:'PDF',fileSize:pf.sizeInBytes,isPrimary:true}),'Attach PDF');
 const both=must(await c.get(`/api/QuestionBank/questions/${q.id}/attachments`),'Read primary selection');
 e.check('Only latest requested primary attachment remains primary',both.filter(x=>x.isPrimary).length===1&&both.find(x=>x.id===pa.id).isPrimary,both);
 must(await c.request('PATCH',`/api/QuestionBank/attachments/${at.id}/set-primary`),'Switch primary');
 must(await c.put(`/api/QuestionBank/attachments/${pa.id}`,{...pa,fileName:'QA26 PDF renamed',isPrimary:false}),'Rename attachment');
 e.check('Attachment rename persists',must(await c.get(`/api/QuestionBank/questions/${q.id}/attachments`),'Read attachment rename').some(x=>x.fileName==='QA26 PDF renamed'));
 must(await c.delete(`/api/QuestionBank/attachments/${pa.id}`),'Delete PDF attachment');
 e.check('Deleted attachment removed from question',!must(await c.get(`/api/QuestionBank/questions/${q.id}/attachments`),'Read after delete').some(x=>x.id===pa.id));
 bank.deleted.push({attachmentId:pa.id});q.attachments=must(await c.get(`/api/QuestionBank/questions/${q.id}/attachments`),'Final attachments');save();
}
const s=bank.subjects[0],t=bank.topics[0];
must(await c.put(`/api/Lookups/question-subjects/${s.id}`,{nameEn:s.nameEn+' Updated',nameAr:s.nameAr}),'Rename subject');
e.check('Subject rename updates question presentation',must(await c.get(`/api/QuestionBank/questions/${q.id}`),'Read renamed subject').subjectNameEn.endsWith(' Updated'));
must(await c.put(`/api/Lookups/question-subjects/${s.id}`,{nameEn:s.nameEn,nameAr:s.nameAr}),'Restore subject');
must(await c.put(`/api/Lookups/question-topics/${t.id}`,{nameEn:t.nameEn+' Updated',nameAr:t.nameAr,subjectId:s.id}),'Rename topic');
e.check('Topic rename persists',must(await c.get(`/api/Lookups/question-topics/${t.id}`),'Read topic rename').nameEn.endsWith(' Updated'));
must(await c.put(`/api/Lookups/question-topics/${t.id}`,{nameEn:t.nameEn,nameAr:t.nameAr,subjectId:s.id}),'Restore topic');
const deleteTopic=await c.delete(`/api/Lookups/question-topics/${t.id}`);
e.check('Topic with questions cannot be deleted',!deleteTopic.ok&&deleteTopic.status<500,deleteTopic.body);
const deleteSubject=await c.delete(`/api/Lookups/question-subjects/${s.id}`);
e.check('Subject with questions/topics cannot be deleted',!deleteSubject.ok&&deleteSubject.status<500,deleteSubject.body);
save();
console.log(JSON.stringify({checks:e.checks.length,failures:e.checks.filter(x=>!x.passed).map(x=>x.name)},null,2));
